#!/usr/bin/env bash
# Write bundles/all-skills.md and bundles/all-agent-roles.md: every skill and every
# charter combined into one file each, for vendors with a low project file limit.
# The bundles are committed. The workflow fails if they do not match their sources.
set -euo pipefail
cd "$(dirname "$0")/.."
mkdir -p bundles

combine() { # combine <output file> <title> <folder>
  local target="$1" title="$2" folder="$3"
  printf '# %s\n\nGenerated by scripts/build-bundles.sh. Edit the source files, not this file. Each file below follows a line with its path.\n' "$title" > "$target"
  find "$folder" -type f -name '*.md' | LC_ALL=C sort | while read -r file; do
    printf '\n\n===== FILE: %s =====\n\n' "$file" >> "$target"
    cat "$file" >> "$target"
  done
}
combine bundles/all-skills.md "Marketing Office: all skills" skills
combine bundles/all-agent-roles.md "Marketing Office: all agent role charters" agents
combine bundles/context-pack-templates.md "Marketing Office: context pack templates, all 10 in one file" context-pack/templates

# The sample file for the 10-minute trial: the office manual, one skill and the fictional company's pack.
{
  printf '# Marketing Office: try it with a sample company\n\nGenerated by scripts/build-bundles.sh. Everything about CogniATion in this file is fictional. This is a trial: ignore the line in the office manual about loading it into persistent instructions, and follow the rest of it in this chat.\n'
  for file in office/office-manual.md skills/product-marketing-and-sales-enablement/write-sales-one-pager.md context-pack/example-cogniation/*.md; do
    printf '\n\n===== FILE: %s =====\n\n' "$file"
    cat "$file"
  done
} > bundles/try-it.md
echo "build-bundles: wrote 4 files to bundles/"
