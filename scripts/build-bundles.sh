#!/usr/bin/env bash
# Write bundles/all-skills.md and bundles/roles-and-playbooks.md: every skill, and every
# charter and playbook, combined into one file each, for vendors with a low project file limit.
# The bundles are committed. The workflow fails if they do not match their sources.
set -euo pipefail
cd "$(dirname "$0")/.."
# BUNDLE_OUT lets the validator build a fresh copy elsewhere and compare it.
out="${BUNDLE_OUT:-bundles}"
mkdir -p "$out"

combine() { # combine <output file> <title> <folder>
  local target="$1" title="$2" folder="$3"
  printf '# %s\n\nGenerated by scripts/build-bundles.sh. Edit the source files, not this file. Each file below follows a line with its path.\n' "$title" > "$target"
  find "$folder" -type f -name '*.md' | LC_ALL=C sort | while read -r file; do
    printf '\n\n===== FILE: %s =====\n\n' "$file" >> "$target"
    cat "$file" >> "$target"
  done
}
combine "$out/all-skills.md" "Marketing Office: all skills" skills
# Charters and playbooks share a file, so "what should I do next?" can reach the playbooks.
{
  printf '# Marketing Office: agent role charters and playbooks\n\nGenerated by scripts/build-bundles.sh. Edit the source files, not this file. Each file below follows a line with its path.\n'
  find agents playbooks -type f -name '*.md' | LC_ALL=C sort | while read -r file; do
    printf '\n\n===== FILE: %s =====\n\n' "$file"
    cat "$file"
  done
} > "$out/roles-and-playbooks.md"
combine "$out/context-pack-templates.md" "Marketing Office: context pack templates, all 10 in one file" context-pack/templates

# The sample file for the 10-minute trial: the office manual, one skill and the fictional company's pack.
{
  printf '# Marketing Office: try it with a sample company\n\nGenerated by scripts/build-bundles.sh. Everything about CogniATion in this file is fictional. This is a trial: follow the office manual in this chat.\n'
  for file in office/office-manual.md skills/product-marketing-and-sales-enablement/write-sales-one-pager.md context-pack/example-cogniation/*.md; do
    printf '\n\n===== FILE: %s =====\n\n' "$file"
    cat "$file"
  done
} > "$out/try-it.md"
echo "build-bundles: wrote 4 files to $out/"
